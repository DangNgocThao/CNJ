    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        // TODO add your handling code here:
        int pos = this.tb1Emp.getSelectedRow();
        if (pos >= 0) {
            String code = (String) (tb1Emp.getValueAt(pos, 0));
            if (JOptionPane.showConfirmDialog(this, "Delete the " + code + " employee ?") == JOptionPane.OK_OPTION) {
                data.remove(pos);
                tb1Emp.updateUI();
                changed = true;
            }
        }
    }//GEN-LAST:event_btnRemoveActionPerformed

    private void tb1EmpMouseReleased(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tb1EmpMouseReleased
        // TODO add your handling code here:
        if (this.tb1Emp.isEditing()) {
            int row = tb1Emp.getSelectedRow();
            int column = tb1Emp.getSelectedColumn();
            tb1Emp.getCellEditor(row, column).cancelCellEditing();
        }
    }//GEN-LAST:event_tb1EmpMouseReleased

    private void tb1EmpMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tb1EmpMouseClicked
        // TODO add your handling code here:
        int row = this.tb1Emp.getSelectedRow();
        this.txtCode.setText((String) (tb1Emp.getValueAt(row, 0)));
        this.txtCode.setEditable(false);
        this.txtName.setText((String) (tb1Emp.getValueAt(row, 1)));
        this.txtSalary.setText((String) (tb1Emp.getValueAt(row, 2)));
        addNew = false;
    }//GEN-LAST:event_tb1EmpMouseClicked

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        String code = txtCode.getText();
        String name = txtName.getText();
        String salaryStr = txtSalary.getText();
        if (addNew) {
            Vector v = new Vector();
            v.add(code);
            v.add(name);
            v.add(salaryStr);
            data.add(v);
            addNew = false;
        } else {
            int pos = tb1Emp.getSelectedRow();
            Vector v = (Vector) data.get(pos);
            v.set(1, name);
            v.set(2, salaryStr);
        }
        tb1Emp.updateUI();
        changed = true;
    }//GEN-LAST:event_btnSaveActionPerformed

    private void loadData() {
        try {
            File f = new File(filename);
            FileReader fr = new FileReader(f);
            BufferedReader bf = new BufferedReader(fr);
            String aDetails;
            while ((aDetails = bf.readLine()) != null) {
                StringTokenizer stk = new StringTokenizer(aDetails, ",");
                String code = stk.nextToken();
                String name = stk.nextToken();
                String salaryStr = stk.nextToken();
                Vector<String> v = new Vector<String>();
                v.add(code);
                v.add(name);
                v.add(salaryStr);
                data.add(v);
            }
            bf.close();
            fr.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "The file " + filename + " not found.");
        }
    }

