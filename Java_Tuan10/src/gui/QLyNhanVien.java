    private void hienThi() {
        ArrayList<PhongBan> dsPB = phongBanDao.layDanhSachPhongBan();
        dtm.setRowCount(0);
        for (PhongBan pb : dsPB) {
            Vector<Object> v = new Vector<>();
            v.add(pb.getMaPhong());
            v.add(pb.getTenPhong());
            dtm.addRow(v);
        }
        jTable1.setModel(dtm);
    }

