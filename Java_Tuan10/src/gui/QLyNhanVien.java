    private void btnLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuActionPerformed
        // TODO add your handling code here:
        PhongBan pb = new PhongBan();

        if (txtMa.getText().isEmpty()) {
            pb.setTenPhong(txtTen.getText());
            if (phongBanDao.themPhongBan(pb)) {
                JOptionPane.showMessageDialog(this, "Thêm thành công");
            } else {
                JOptionPane.showMessageDialog(this, "Thêm thất bại");
            }
        } else {
            pb.setMaPhong(Integer.parseInt(txtMa.getText()));
            pb.setTenPhong(txtTen.getText());
            if (phongBanDao.capNhatPhongBan(pb)) {
                JOptionPane.showMessageDialog(this, "Cập nhập thành công");
            } else {
                JOptionPane.showMessageDialog(this, "Cập nhập thất bại");
            }
        }
        hienThi();
    }//GEN-LAST:event_btnLuuActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        if (txtMa.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Chọn phòng ban cần xóa");
            return;
        }
        if(JOptionPane.showConfirmDialog(this, "Bạn có muốn xóa phòng ban này không?","Thông báo",JOptionPane.YES_NO_OPTION)==JOptionPane.NO_OPTION){
            return;
        }else{
            PhongBan pb = new PhongBan();
            pb.setMaPhong(Integer.parseInt(txtMa.getText()));
            if (phongBanDao.xoaPhongBan(pb)) {
                JOptionPane.showMessageDialog(this, "Xóa thành công");
            } else {
                JOptionPane.showMessageDialog(this, "Xóa thất bại");
            }
        }
        hienThi();
    }//GEN-LAST:event_btnXoaActionPerformed

