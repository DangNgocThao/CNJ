    private void btnTinhLuongActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTinhLuongActionPerformed
        // TODO add your handling code here:
        if (txtMa.getText().isEmpty() || txtLCB.getText().isEmpty() || txtSoNLV.getText().isEmpty() || txtTroCap.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "bạn phải điền đầy đủ thông tin");
            return;
        }
        double lcb = Double.parseDouble(txtLCB.getText());
        int snlv = Integer.parseInt(txtSoNLV.getText());
        double tc = Double.parseDouble(txtTroCap.getText());
        if (lcb <= 0) {
            JOptionPane.showMessageDialog(this, "Lương cơ bản phải lớn hơn 0");
        }
        if (snlv <= 0) {
            JOptionPane.showMessageDialog(this, "Số ngày làm việc phải lớn hơn 0");
        } else {

            if (snlv <= 22) {
                double kq = lcb + snlv * 100000 + tc;
                txtLuongThang.setText(kq + "");
            } else {
                double kq = lcb + 22 * 100000 + (snlv - 22) * 150000 + tc;
                txtLuongThang.setText(kq + "");
            }
        }

    }//GEN-LAST:event_btnTinhLuongActionPerformed

