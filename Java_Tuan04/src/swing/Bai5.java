    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        String name = txtName.getText();
        String email = txtEmail.getText();
        String date = txtDate.getText();

        if (ktName(name) && ktDate(date) && ktEmail(email)) {
            try {
                FileWriter fr = new FileWriter("src\\Swing\\dulieu.txt", true);
                BufferedWriter bw = new BufferedWriter(fr);
                bw.write(name + ", " + date + ", " + email + ", ");
                if (rdoMale.isSelected()) {
                    bw.write("Nam, ");
                } else {
                    bw.write("Nữ, ");
                }
                bw.write(cbo.getSelectedItem().toString() + "\n");
                bw.close();
                JOptionPane.showMessageDialog(this, "Đăng kí thành công!", "Success", JOptionPane.INFORMATION_MESSAGE);
            } catch (Exception e) {
                e.printStackTrace();
            }
        } else {
            JOptionPane.showMessageDialog(this, "Thông tin không hợp lệ", "ERROR", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

