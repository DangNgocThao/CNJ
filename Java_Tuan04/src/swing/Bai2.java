    private void btnGiaiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGiaiActionPerformed
        // TODO add your handling code here:
        double a = Double.parseDouble(txtA.getText());
        double b = Double.parseDouble(txtB.getText());
        double c = Double.parseDouble(txtC.getText());
        if (a == 0) {
            if (b == 0) {
                if (c == 0) {
                    txtKQ.setText("PT có vô số nghiệm");
                } else {
                    txtKQ.setText("PT vô nghiệm");
                }
            } else {
                txtKQ.setText("PT có 1 nghiệm: " + (-c / b));
            }
        } else {
            double d = b * b - 4 * a * c;
            if (d < 0) {
                txtKQ.setText("PT vô nghiệm");
            } else if (d == 0) {
                double x = -b / (a * 2);
                txtKQ.setText("PT có 1 nghiệm kép: " + x);
            } else {
                double x1 = (-b + sqrt(d)) / (2 * a);
                double x2 = (-b - sqrt(d)) / (2 * a);
                txtKQ.setText("PT có 2 nghiệm phân biệt: x1 = " + x1 + ", x2 = " + x2);
            }
        }
    }//GEN-LAST:event_btnGiaiActionPerformed

