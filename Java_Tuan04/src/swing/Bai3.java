    private void btnGiaiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGiaiActionPerformed
        // TODO add your handling code here:
        double a, b;
        if (txtA.getText().equals("") || txtB.getText().equals("")) {
            return;
        }
        a = Double.parseDouble(txtA.getText());
        b = Double.parseDouble(txtB.getText());
        if (buttonGroup1.getSelection().equals(rdoCong.getModel())) {
            txtKQ.setText("" + (a + b));
        } else if (buttonGroup1.getSelection().equals(rdoTru.getModel())) {
            txtKQ.setText("" + (a - b));
        } else if (buttonGroup1.getSelection().equals(rdoNhan.getModel())) {
            txtKQ.setText("" + (a * b));
        } else
            txtKQ.setText("" + (a / b));
    }//GEN-LAST:event_btnGiaiActionPerformed

