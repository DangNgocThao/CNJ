    private void btnPhanSoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPhanSoActionPerformed
        // TODO add your handling code here:
        if (txt.getText().equals("")) {
            return;
        }

        String s = evt.getActionCommand();

        try {
            double t = Double.parseDouble(txt.getText());
            if (s.equals("sqrt")) {
                t = Math.sqrt(t);
            } else if (s.equals("%")) {
                t = t * 100;
            } else if (s.equals("1/x")) {
                t = 1 / t;
            }

            txt.setText("" + t);
            kt = true;
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnPhanSoActionPerformed

