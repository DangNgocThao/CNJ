    private void btnBangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBangActionPerformed
        // TODO add your handling code here:
        if (txt.getText().equals("") || so.equals("")) {
            return;
        }

        try {
            double so1 = Double.parseDouble(so);
            double so2 = Double.parseDouble(txt.getText());
            double kq = 0;
            if (dau.equals("+")) {
                kq = so1 + so2;
            } else if (dau.equals("-")) {
                kq = so1 - so2;
            } else if (dau.equals("*")) {
                kq = so1 * so2;
            } else if (dau.equals("/")) {
                kq = so1 / so2;
            }

            txt.setText("" + kq);
            kt = true;
            so = "";
            dau = "";
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnBangActionPerformed

