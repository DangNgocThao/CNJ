    private void hienThi() {
        try {
            String sql = "Select * from CDDVDCOLECTION";
            preparedStatement = connection.prepareStatement(sql);
            resultSet = preparedStatement.executeQuery();
            dtm.setRowCount(0);
            while (resultSet.next()) {
                String ma = resultSet.getString(1);
                String tieuDe = resultSet.getString(2);
                String loai = resultSet.getString(3);
                int nam = resultSet.getInt(4);
                Vector<Object> v = new Vector<Object>();
                v.add(ma);
                v.add(tieuDe);
                v.add(loai);
                v.add(nam);
                dtm.addRow(v);
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
    
    private boolean ktMa(String text) {
        try {
            String sql = "Select * from CDDVDCOLECTION where MA=?";
            preparedStatement = connection.prepareStatement(sql);
            preparedStatement.setString(1, text);
            resultSet = preparedStatement.executeQuery();
            if (resultSet.next()) {
                return true;
            } else {
                return false;
            }
        } catch (Exception e) {
        }
        return false;
    }
    
    private void themCSDL(String ma, String tieuDe, String loai, String nam) {
        try {
            String sql = "insert into CDDVDCOLECTION values(?,?,?,?)";
            preparedStatement = connection.prepareStatement(sql);
            preparedStatement.setString(1, ma);
            preparedStatement.setString(2, tieuDe);
            preparedStatement.setString(3, loai);
            preparedStatement.setInt(4, Integer.parseInt(nam));
            int x = preparedStatement.executeUpdate();
            if (x >= 1) {
                JOptionPane.showMessageDialog(this, "Thêm thành công");
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
    
    private void capNhatCSDL(String ma, String tieuDe, String loai, String nam) {
        try {
            String sql = "update CDDVDCOLECTION set TIEUDE=?,LOAIDIA=?,NAMXB=? where MA=?";
            preparedStatement = connection.prepareStatement(sql);
            
            preparedStatement.setString(1, tieuDe);
            preparedStatement.setString(2, loai);
            preparedStatement.setInt(3, Integer.parseInt(nam));
            preparedStatement.setString(4, ma);
            int x = preparedStatement.executeUpdate();
            if (x >= 1) {
                JOptionPane.showMessageDialog(this, "Cập nhật thành công");
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
    
    private void xoaCSDL(String ma) {
        try {
            String sql = "delete from CDDVDCOLECTION where MA=?";
            preparedStatement = connection.prepareStatement(sql);
            preparedStatement.setString(1, ma);
            int x = preparedStatement.executeUpdate();
            if (x >= 1) {
                JOptionPane.showMessageDialog(this, "Số dòng đã xóa: " + x);
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
