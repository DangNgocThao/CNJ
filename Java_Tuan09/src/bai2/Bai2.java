    private void btnLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuActionPerformed
        // TODO add your handling code here:
        if (txtMa.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mã khách hàng không được để trống");
            return;
        }
        if (ktMa(txtMa.getText()) == true) {
            int n = JOptionPane.showConfirmDialog(this, "Thông báo", "Bạn muốn cập nhật dữ liệu không?", JOptionPane.YES_NO_OPTION);
            if (n == JOptionPane.NO_OPTION) {
                return;
            } else {
                capNhatCSDL(txtMa.getText(), txtTieuDe.getText(), txtLoai.getText(), txtNam.getText());
                hienThi();
            }
        } else {
            themCSDL(txtMa.getText(), txtTieuDe.getText(), txtLoai.getText(), txtNam.getText());
            hienThi();
        }
    }//GEN-LAST:event_btnLuuActionPerformed

