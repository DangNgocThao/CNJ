    private void hienThi() {
        try {
            String sql = "Select * from CDDVDCOLECTION";
            preparedStatement = connection.prepareStatement(sql);
            resultSet = preparedStatement.executeQuery();
            dtm.setRowCount(0);
            while (resultSet.next()) {
                String ma = resultSet.getString(1);
                String tieuDe = resultSet.getString(2);
                String loai = resultSet.getString(3);
                int nam = resultSet.getInt(4);
                Vector<Object> v = new Vector<Object>();
                v.add(ma);
                v.add(tieuDe);
                v.add(loai);
                v.add(nam);
                dtm.addRow(v);
            }
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }

    private void loadTable(String key) {
        try {
            dtm.setRowCount(0);
            String sql;
            if (key.isEmpty()) {
                sql = "select * from CDDVDCOLECTION";
                preparedStatement = connection.prepareStatement(sql);
            } else {
                sql = "select * from CDDVDCOLECTION where MA like ? or TIEUDE like ? or LOAIDIA like ? or NAMXB like ?";
                preparedStatement = connection.prepareStatement(sql);
                preparedStatement.setString(1, "%" + txtTim.getText() + "%");
                preparedStatement.setString(2, "%" + txtTim.getText() + "%");
                preparedStatement.setString(3, "%" + txtTim.getText() + "%");
                preparedStatement.setString(4, "%" + txtTim.getText() + "%");
            }
            resultSet = preparedStatement.executeQuery();
            while (resultSet.next()) {
                Vector<Object> vector = new Vector<>();
                vector.add(resultSet.getString("MA"));
                vector.add(resultSet.getString("TIEUDE"));
                vector.add(resultSet.getString("LOAIDIA"));
                vector.add(resultSet.getInt("NAMXB"));
                dtm.addRow(vector);
            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

