    private void btnLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuActionPerformed
        // TODO add your handling code here:
        if (txtMa.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Mã khách hàng không được để trống");
        }
        if (ktMa(txtMa.getText())) {
            int n = JOptionPane.showConfirmDialog(this, "Bạn muốn cập nhật dữ liệu không?", "Thông báo", JOptionPane.YES_NO_OPTION);
            if (n == JOptionPane.NO_OPTION) {
                return;
            } else {
                capNhatCSDL(txtMa.getText(), txtTen.getText(), txtNam.getText());
                hienThi();
            }
        } else {
            themCSDL(txtMa.getText(), txtTen.getText(), txtNam.getText(), "n1");
            hienThi();
        }
    }//GEN-LAST:event_btnLuuActionPerformed

