    private void hienThi() {
        try {
            String sql = "Select MaKH,TenKH,NamSinh from KhachHang";
            resultSet = statement.executeQuery(sql);
            dtm.setRowCount(0);
            while (resultSet.next()) {
                String ma = resultSet.getString("MaKH");
                String ten = resultSet.getString("TenKH");
                int nam = resultSet.getInt("NamSinh");
                Vector<Object> v = new Vector<Object>();
                v.add(ma);
                v.add(ten);
                v.add(nam);
                dtm.addRow(v);
            }
        } catch (SQLException ex) {
            Logger.getLogger(QL_KhachHang.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
