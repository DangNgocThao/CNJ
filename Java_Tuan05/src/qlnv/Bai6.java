    private void lstNVMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_lstNVMousePressed
        // TODO add your handling code here:
        NhanVien nv = (NhanVien) lstNV.getSelectedValues()[0];
        SimpleDateFormat formatter = new SimpleDateFormat("dd/MM/yyyy");
        String ngayvl = formatter.format(nv.getNgayVL());
        String namsinh = formatter.format(nv.getNgaySinh());
        txtMa.setText(nv.getMaSo());
        txtTen.setText(nv.getHoTen());
        txtNgayVL.setText(ngayvl);
        txtNamSinh.setText(namsinh);
    }//GEN-LAST:event_lstNVMousePressed

    private void btnLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuActionPerformed
        // TODO add your handling code here:
        NhanVien newNV = new NhanVien();

        newNV.setMaSo(txtMa.getText());
        newNV.setHoTen(txtTen.getText());
        try {
            newNV.setNgayVL(new SimpleDateFormat("dd/MM/yyyy").parse(txtNgayVL.getText()));
        } catch (ParseException ex) {
            Logger.getLogger(Bai6.class.getName()).log(Level.SEVERE, null, ex);
        }
        try {
            newNV.setNgaySinh(new SimpleDateFormat("dd/MM/yyyy").parse(txtNamSinh.getText()));
        } catch (ParseException ex) {
            Logger.getLogger(Bai6.class.getName()).log(Level.SEVERE, null, ex);
        }

        PhongBan pb = (PhongBan) cboPhongBan.getSelectedItem();
        newNV.setPhong(pb);
        pb.themNV(newNV);
        reLoadList();
    }//GEN-LAST:event_btnLuuActionPerformed

